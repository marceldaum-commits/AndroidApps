package de.raumlicht.core.model

/** Eine Theorie-Karte: kurz, mit Merkbild, Schritten, Mini-Beispiel und typischem Fehler */
data class TheoryCard(
    val key: String,            // eindeutiger Schlüssel, z. B. "durchstoss"
    val emoji: String,          // Merkbild
    val title: String,          // z. B. "Durchstoßpunkt"
    val idea: String,           // ein bis zwei Sätze von Lux: worum es geht, anschaulich (Bühne, Laser, Scheiben …)
    val steps: List<String>,    // 2–4 Schritte „So gehst du vor“ – kurze Zeilen, Formeln in der Schreibweise der App
    val example: List<String>,  // ein durchgerechnetes Mini-Beispiel in 2–4 Zeilen, mit ANDEREN Zahlen als in den Aufgaben
    val trap: String,           // typischer Fehler in einem Satz (ohne „Achtung“ am Anfang – das setzt die Oberfläche)
    val sheet: Int? = null,     // Index der passenden Karte in Sheet.cards (Formelsammlung) oder null
) {
    /** Die Formel, die man für die Aufgaben dieser Karte braucht, samt Bedeutung der Größen – steht in der Anzeige ganz oben */
    val formula: Formula? get() = TheoryFormulas.of(key)
}

