package de.kurvenflug.app

// Brücke zu kf.js (liegt neben index.html): Ton, Speicher, Teilen, Zurück-Taste. Alles bleibt im Browser.

internal fun jsStoreGet(key: String): String? = js("window.localStorage.getItem(key)")
internal fun jsStoreSet(key: String, value: String): Unit = js("(function () { try { window.localStorage.setItem(key, value) } catch (e) {} })()")
internal fun jsStoreRemove(key: String): Unit = js("window.localStorage.removeItem(key)")
internal fun jsStoreKeys(): String = js("Object.keys(window.localStorage).join(String.fromCharCode(10))")

internal fun jsShare(text: String, title: String): Unit = js("window.KF.share(text, title)")
internal fun jsOpen(url: String): Unit = js("window.open(url, '_blank', 'noopener')")
internal fun jsVibrate(ms: Int): Unit = js("(function () { try { if (navigator.vibrate) navigator.vibrate(ms) } catch (e) {} })()")
internal fun jsPhoto(spec: String, title: String): Unit = js("window.KF.photo(spec, title)")

internal fun jsBufNew(n: Int, rate: Int): Int = js("window.KF.bufNew(n, rate)")
internal fun jsBufSet(id: Int, i: Int, v: Double): Unit = js("window.KF.bufData[id][i] = v")
internal fun jsBufDone(id: Int): Unit = js("window.KF.bufDone(id)")
internal fun jsPlay(id: Int, rate: Double, volume: Double): Unit = js("window.KF.play(id, rate, volume)")
internal fun jsMusic(id: Int, volume: Double): Unit = js("window.KF.music(id, volume)")
internal fun jsOnBack(handler: () -> Boolean): Unit = js("window.KF.onBack(handler)")
internal fun jsOnUnlock(handler: () -> Unit): Unit = js("window.KF.onUnlock(handler)")

// Vorlesen mit Nova (kf.js, Abschnitt „Vorlesen“)
internal fun jsOnSpeaking(f: (Boolean) -> Unit): Unit = js("window.KF.onSpeaking(f)")
internal fun jsNova(items: String): Unit = js("window.KF.nova(items)")
internal fun jsOnUnreach(f: () -> Unit): Unit = js("window.KF.onUnreach(f)")
internal fun jsHush(): Unit = js("window.KF.hush()")
internal fun jsInstallMode(): String = js("(window.kfInstallMode ? window.kfInstallMode() : '')")
internal fun jsInstall(): Unit = js("(function () { if (window.kfInstall) window.kfInstall() })()")
internal fun jsElternLink(): String = js("(window.KF && window.KF.elternLink ? window.KF.elternLink() : '')")
internal fun jsElternPair(nick: String): String = js("window.KF.elternPair(nick)")
internal fun jsElternUnpair(): Unit = js("window.KF.elternUnpair()")
internal fun jsElternNick(): String = js("(window.KF && window.KF.elternNick ? window.KF.elternNick() : '')")
internal fun jsElternReport(json: String): Unit = js("(function () { if (window.KF && window.KF.elternReport) window.KF.elternReport(json) })()")
internal fun jsElternRestore(link: String, force: Boolean, cb: (String) -> Unit): Unit = js("window.KF.elternRestore(link, force, cb)")
internal fun jsCountNow(body: String): Unit = js("(function () { try { fetch('https://trainer.mathenachhilfe-online.com/zaehler/v1/e', { method: 'POST', credentials: 'omit', keepalive: true, headers: { 'Content-Type': 'text/plain' }, body: body }).catch(function () {}); } catch (e) {} })()")
internal fun jsAllApps(): Unit = js("window.KF.allApps()")
internal fun jsMode(): String = js("(window.kfMode || '')")
internal fun jsOnLeave(f: () -> String): Unit = js("(function () { if (window.KF && window.KF.onLeave) window.KF.onLeave(f) })()")
internal fun jsAtHome(home: Boolean): Unit = js("(function () { if (window.kfAtHome) window.kfAtHome(home) })()")
internal fun jsNovaSpeed(speed: Double): Unit = js("window.KF.novaSpeed(speed)")
internal fun jsOffStat(hashes: String, cb: (Int, Int, Double, Double, Double) -> Unit): Unit = js("window.KF.offStat(hashes, cb)")
internal fun jsOffLoad(hashes: String, best: Boolean, progress: (Int, Int) -> Unit, done: (Int, Boolean) -> Unit): Unit = js("window.KF.offLoad(hashes, best, progress, done)")
internal fun jsOffCancel(): Unit = js("window.KF.offCancel()")
internal fun jsOffClear(cb: () -> Unit): Unit = js("window.KF.offClear(cb)")
internal fun jsText(url: String, cb: (String) -> Unit): Unit = js("fetch(url).then(function (r) { return r.ok ? r.text() : ''; }).then(cb, function () { cb(''); })")
